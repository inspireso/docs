# 个税计算
def tax(salary):
    rate = [
        (0, 36000, 0.03, 0),
        (36000, 144000, 0.1, 2520),
        (144000, 300000, 0.2, 16920),
        (300000, 420000, 0.25, 31920),
        (420000, 660000, 0.3, 52920),
        (660000, 960000, 0.35, 85920),
        (960000, 999999999, 0.45, 181920),
    ]

    for a, b, c, d in rate:
        if a < salary <= b:
            tax = salary * c - d
            print(f'{salary:.2f}: {c * 100}%')
            return tax
    return 0
